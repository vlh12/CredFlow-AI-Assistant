CREATE TABLE CF_AUTH.CF_LOAN_DRAFTS (
 DRAFT_ID VARCHAR2(36) PRIMARY KEY,
 SELLER_ID VARCHAR2(36) NOT NULL REFERENCES CF_AUTH.CF_SELLER_PROFILES(SELLER_ID),
 FIELDS_JSON CLOB DEFAULT '{}' NOT NULL CHECK (FIELDS_JSON IS JSON),
 DRAFT_STATUS VARCHAR2(24) DEFAULT 'DRAFT' NOT NULL CHECK (DRAFT_STATUS IN ('DRAFT','READY_FOR_REVIEW','SUBMITTED')),
 ROW_VERSION NUMBER(10) DEFAULT 0 NOT NULL,
 REQUEST_ID VARCHAR2(36),
 CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX CF_AUTH.IX_CF_DRAFT_SELLER ON CF_AUTH.CF_LOAN_DRAFTS(SELLER_ID,DRAFT_STATUS,UPDATED_AT);
